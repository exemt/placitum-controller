/**
 * Какие переменные читает страница отказа.
 *
 * У записи `waf_deny_response` два независимых поля: страница (`page=`) и
 * перечень того, что ей отдать (`params=`). Ни одно из них не знает про
 * другое: перечень открывает переменную, которой в шаблоне нет, или запирает
 * ту, ради которой ветка написана, -- и узнаётся это на живом отказе, у
 * клиента, то есть там, где смотреть уже поздно.
 *
 * Поэтому имена читаются из самого тела. Это не SSI-интерпретатор: нужен
 * список имён, а не результат подстановки, и веток разбор не считает --
 * переменная, упомянутая в недостижимой ветке, всё равно упомянута.
 *
 * Считается на чтении набора, а не пишется колонкой в базу: тело приезжает и
 * миграцией (встроенные страницы сеются сидом), и ручкой содержимого;
 * колонка, которую забыли обновить в одном из двух мест, молча соврала бы про
 * страницу.
 */

/*
 * Директива SSI целиком: имя команды и её аргументы. Хвост нежадный -- иначе
 * первая директива на странице съела бы всё до последнего `-->`.
 */
const DIRECTIVE = /<!--#\s*(\w+)([^]*?)-->/g;

/** `<!--# echo var="waf_deny_ray" default="" -->` */
const ECHO_VAR = /var=["']([^"']*)["']/;

/** `<!--# if expr="$waf_deny_scope = network" -->` */
const COND_EXPR = /expr=["']([^"']*)["']/;

/**
 * Имена переменных, которые страница печатает или проверяет. Отсортированы и
 * без повторов: список уезжает в панель как свойство набора, а не как порядок
 * появления в файле.
 *
 * Имя без `$` -- в `echo` его пишут голым, в `expr` со знаком; здесь это одно
 * и то же имя, потому что и открывает, и запирает их одна и та же запись.
 */
export function pageVars(body: string): string[] {
  const found = new Set<string>();

  DIRECTIVE.lastIndex = 0;

  let m: RegExpExecArray | null;

  while ((m = DIRECTIVE.exec(body)) !== null) {
    const [, cmd, args] = m;

    if (cmd === "echo") {
      const name = ECHO_VAR.exec(args)?.[1] ?? "";

      if (name !== "") {
        found.add(name);
      }

      continue;
    }

    if (cmd === "if" || cmd === "elif") {
      const expr = COND_EXPR.exec(args)?.[1] ?? "";

      for (const hit of expr.matchAll(/\$(\w+)/g)) {
        found.add(hit[1]);
      }
    }
  }

  return [...found].sort();
}
