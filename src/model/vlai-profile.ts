/**
 * Профиль инспектора vlai: классификатор серьёзности, вердикт всегда score
 * либо allow. Профиль поэтому короткий -- он не описывает модель и шкалу
 * (это свойство процесса), а отвечает на три вопроса политики:
 *
 *   - режим: судить, наблюдать или молчать (`mode`);
 *   - что делать, когда очередь процесса полна (`overload`);
 *   - канал действий: чьи просьбы слушать (`trigger.prior`) и что говорить
 *     соседям самому (`outcomes`).
 *
 * Форма документа повторяет YAML загрузчика (inspectors/vlai/src/profiles.py):
 * расхождение между ними -- не стиль, а поколение, которое инспектор
 * отвергнет как apply_failed.
 */


/**
 * Очередь полна. `allow` -- ответить пропуском сразу (fail-open, умолчание),
 * `wait` -- стоять в очереди до дедлайна, `deny` -- отказать сразу
 * (fail-closed для маршрутов, где непроверенный текст дороже отказа).
 */
/**
 * Полная очередь: стоять до дедлайна (`wait`) или ответить сразу (`shed`).
 * Судьбу такого запроса называет маршрут -- `waf_exception … inspector`, --
 * а инспектор отвечает вердиктом `error`. Прежние `allow` и `deny` сняты
 * (091): они решали за маршрут и мимо конфигурации nginx.
 */
export type VlaiOverload = "wait" | "shed";

/** Правило приёма чужих просьб. Оба глагола умеют ослаблять, поэтому
 * широковещательного правила у этого инспектора не бывает. */
export interface VlaiPriorRule {
  from: string;
  accept: ("threshold" | "skip")[];
  codes: string[];
}

/**
 * Инициатор по исходу: собственное решение фазы просит соседа либо вносит
 * адрес клиента в живой набор. Триггеров два: `score` -- счёт против порога,
 * `overload` -- запрос снят на входе из-за полной очереди. Действие ровно
 * одно: непустой `do` -- просьба, непустой `list` -- запись.
 */
import type { ArchiveWhen, RecordObject } from "./actions.ts";

export interface VlaiOutcome {
  on: "score" | "overload";
  /** Порог; только при on: score, обязателен там. */
  at: number | null;
  /** Сравнение в другую сторону: score < at. */
  below: boolean;
  /** Ровно at. С below взаимоисключимо. */
  eq: boolean;
  /** Адресат просьбы обязателен: «всем» здесь нет. */
  to: string;
  do: string;
  apply: string;
  /** Только threshold: проценты коэффициента, −100..900. */
  delta: number | null;
  /** Только note: проценты шкалы счётчика получателя, −100..100. */
  value: number | null;
  /** Только note: имя корзины получателя — селектор поверх его правил. */
  counter: string;
  /**
   * Метка события при `do: mark`, обязательна: произвольная строка оператора.
   * Модуль кладёт её в маркеры записи, по которым события ищут и группируют.
   */
  marker: string;
  /** Только mutate, оба обязательны: какую группу модификаторов получателя переключить и куда. */
  group: string;
  /** Только управляющие глаголы: вызову какой фазы адресата ставить режим; пусто -- всем. */
  phase?: string;
  /**
   * У mutate -- куда переключить группу; у глаголов записи (audit, archive)
   * -- писать или нет; objects и limit -- только у archive с set on: какие
   * объекты оставить агенту и сколько байт. Срок архива -- тот же ttlS, что у
   * записи в набор: у строки либо просьба, либо запись.
   */
  set: "on" | "off" | "";
  headers: RecordObject | null;
  args: RecordObject | null;
  body: RecordObject | null;
  /**
   * Только archive с set on: на каких исходах маршрута просьбу исполнять --
   * как when= директивы. Пусто -- на любом, включая перенаправление: просьба
   * сильнее when= маршрута, о котором отправитель не знает.
   */
  when: ArchiveWhen[];
  /** Запись в живой набор: имя набора. */
  list: string;
  /**
   * Кого писать: адрес клиента; эффективный анонс (net); все анонсы,
   * накрывающие адрес (net_all); систему целиком (asn). Подсеть и систему
   * vlai берёт у кодера гео и пишет одной пачкой.
   */
  write: "addr" | "net" | "net_all" | "asn";
  ttlS: number;
  code: string;
}

export interface VlaiProfileDoc {
  description: string;
  overload: VlaiOverload;
  trigger: { prior: VlaiPriorRule[] };
  outcomes: VlaiOutcome[];
}

export interface VlaiProfile {
  id: string;
  httpSpaceId: string;
  name: string;
  description: string;
  doc: VlaiProfileDoc;
  createdAt: Date;
  updatedAt: Date;
}
