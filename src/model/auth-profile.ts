/*
 * Профиль калитки (inspectors/auth): политика допуска одного маршрута.
 *
 * Всё про сам вход -- провайдер, форма, сессии -- живёт в источнике
 * (model/auth-source.ts); профиль называет его ключом doc.source и добавляет
 * режим, условия допуска и правила приёма чужих просьб. Профили одного
 * источника принимают сессии друг друга; разных -- независимы.
 *
 * Документ повторяет форму profile.yaml инспектора один в один.
 */


/**
 * Глаголы, которые калитка умеет применять. Остальной словарь ей не адресован:
 * challenge проводит капча, порога и памяти про субъектов у калитки нет.
 */
import type { ArchiveWhen, RecordObject } from "./actions.ts";

export type AuthVerb = "reauth" | "skip";
/** Оси, встречающиеся при этих глаголах: reauth — session, skip — request. */
export type AuthAxis = "request" | "session";

/**
 * Что профиль принимает от соседа. Единственное место, где чужое высказывание
 * что-то значит: без правила действие не применяется вовсе.
 *
 * Числовых глаголов калитка не применяет. Форма и ограничения --
 * docs/inspector-actions.md.
 */
export interface AuthPriorRule {
  /** Имя отправителя; `*` -- любой. */
  from: string;
  accept: AuthVerb[];
  /** Какие оси принимаем. Пусто -- любая допустимая при этих глаголах. */
  apply: AuthAxis[];
  /** Ограничить правило поводами. Пусто -- любой повод. */
  codes: string[];
}

export interface AuthTrigger {
  prior: AuthPriorRule[];
  /**
   * Возраст сессии, с которого действует просьба reauth. Моложе -- клиент
   * только что вошёл, и гонять его на форму той же просьбой значило бы
   * зациклить вход. 0 -- свежесть не проверяется.
   */
  reauthAfterS: number;
}

export interface AuthGate {
  redirectMethods: string[];
  redirectStatus: number;
  denyResponse: string;
  htmlOnly: boolean;
  /*
   * Допуск по группам: вошедший обязан состоять хотя бы в одной. Пусто --
   * достаточно самого факта входа, и это обычное состояние профиля.
   *
   * Проверяет их инспектор по сессии, а не провайдер на входе: профиль
   * закрытой зоны принимает сессию, выданную формой общего источника, своего
   * входа не видя вовсе. Отсюда пара профилей на один источник: общий пускает
   * всех вошедших, закрытый -- только своих, и второго входа не требуется.
   */
  groups: string[];
  /*
   * Запись каталога отказов для чужой группы (403). Отдельная от
   * denyResponse, потому что говорит другое: тот -- 401 «войдите», этот --
   * «вошли, но не сюда». Одна запись на оба случая врала бы вошедшему.
   */
  forbiddenResponse: string;
  /*
   * Имя записи каталога отказов, отдающей форму входа телом ответа вместо
   * редиректа на неё. false -- прежнее поведение (30x на login.uri). true --
   * навигационный запрос без сессии получает deny с записью denyResponse, а
   * форму инспектор кладёт в обменник и называет модулю секцией rewrite: тот
   * отдаёт её телом ответа на том же URI. Так адрес не меняется, промах
   * редиректа по порту (nginx достраивает его портом своего listen) исчезает
   * вовсе, а записи каталога и прокси-локации для этого не нужно.
   */
  inline: boolean;
}

/**
 * События правил. Все четыре случаются на волне инспектора, но просьба соседу
 * доедет только с allow: отказ и редирект обрывают фазу, поэтому у anonymous,
 * invalid и forbidden загрузчик пускает лишь глаголы записи маршрута.
 */
export const AUTH_ONS = ["authenticated", "anonymous", "invalid", "forbidden", "overload"] as const;

export type AuthOn = (typeof AUTH_ONS)[number];

/**
 * Правило по событию: «когда → что сделать», та же форма, что у правил капчи
 * и строк профиля адреса. Действие ровно одно: просьба соседу либо запись
 * адреса клиента в живой набор.
 */
export interface AuthEventRule {
  on: AuthOn;
  /** Только у on: overload: порог заполнения очереди в процентах; пусто -- край. */
  at?: number | null;

  /* Просьба соседу -- форма канала действий, общая с остальными отправителями. */
  to: string;
  do: string;
  apply: string;
  delta: number | null;
  value: number | null;
  /** note: имя корзины получателя — селектор поверх его правил приёма. */
  counter: string;
  /** mark: метка события на записи, обязательна. */
  marker: string;
  /** mutate: какую группу модификаторов получателя переключить; оба поля обязательны. */
  group: string;
  /** Только управляющие глаголы: вызову какой фазы адресата ставить режим; пусто -- всем. */
  phase?: string;
  /** У mutate -- куда переключить группу; у audit / archive -- писать или нет. */
  set: "on" | "off" | "";
  headers: RecordObject | null;
  args: RecordObject | null;
  body: RecordObject | null;
  /** Только archive с set on: исходы маршрута, на которых просьбу исполнять. */
  when: ArchiveWhen[];

  /* Запись в живой набор: имя набора, кого писать и срок. */
  list: string;
  /**
   * Кого писать: адрес клиента; эффективный анонс, самый узкий (net); все
   * анонсы, накрывающие адрес (net_all); систему целиком (asn). Подсеть и
   * систему разворачивает инспектор у кодера гео.
   */
  write: "addr" | "net" | "net_all" | "asn";
  /** Срок: у записи в набор -- срок записи, у archive с set on -- срок архива. */
  ttlS: number;

  code: string;
}

export interface AuthProfileDoc {
  /*
   * Имя источника входа. Пусто -- профиль ничего не проверяет (контроллер
   * печатает такому `mode: "off"`); с источником -- и защита, и
   * observe открывают сессии, а без источника непонятно даже, какую куку
   * читать.
   */
  source: string;
  gate: AuthGate;
  trigger: AuthTrigger;
  /** Правила по событиям волны: что калитка говорит соседям и маршруту. */
  rules: AuthEventRule[];
}

export interface AuthProfileMeta {
  id: string;
  httpSpaceId: string;
  name: string;
  description: string;
  source: string;
  createdAt: Date;
  updatedAt: Date;
}

export interface AuthProfile extends AuthProfileMeta {
  doc: AuthProfileDoc;
}
