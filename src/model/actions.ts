/** Оси, допустимые хотя бы при одном из выбранных глаголов. */
export function axesFor(verbs: readonly string[]): ActionAxis[] {
  const out = new Set<ActionAxis>();

  for (const spec of ACTIONS) {
    if (!verbs.includes(spec.do)) {
      continue;
    }

    for (const axis of spec.axes) {
      out.add(axis);
    }
  }

  return ACTION_AXES.filter((axis) => out.has(axis));
}

export function actionSpec(verb: string): ActionSpec | undefined {
  return ACTIONS.find((spec) => spec.do === verb);
}

/**
 * Глаголы, которые имеет смысл предлагать в правилах этого инспектора.
 * Слушатели перечислены явно: у каждого получателя свой короткий список
 * входных действий, и предлагать глагол тому, чей загрузчик его отвергнет, --
 * способ собрать мышью правило, которое не сохранится. Пустой `listeners`
 * по-прежнему означает «кому угодно» -- на случай глагола, который правда
 * понимает всякий.
 *
 * Это подсказка панели, а не проверка. Отказывает всё равно загрузчик профиля:
 * он один знает, что `reauth` -- не его дело, и знает это раньше, чем панель
 * успеет спросить.
 */
export function verbsFor(inspector: string): ActionVerb[] {
  return ACTIONS.filter(
    (spec) =>
      spec.module !== true &&
      (spec.listeners.length === 0 || spec.listeners.includes(inspector)),
  ).map((spec) => spec.do);
}

/** Глаголы, которые исполняет модуль: правила приёма у получателей им не нужны. */
export function moduleVerbs(): ActionVerb[] {
  return ACTIONS.filter((spec) => spec.module === true).map((spec) => spec.do);
}

/**
 * Глаголы, чей адресат -- запись самого маршрута, а не вызов соседа: журнал,
 * архив и маркер. Панель показывает их псевдоадресату «запись маршрута».
 */
export function routeVerbs(): ActionVerb[] {
  return ACTIONS.filter((spec) => spec.route === true).map((spec) => spec.do);
}
