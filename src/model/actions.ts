/**
 * Предел длины метки (`marker` у `mark`), байт. Та же граница, которой
 * отбраковывает модуль: длиннее -- отброшен весь ответ инспектора, поэтому
 * собрать такой профиль нельзя ни панелью, ни файлом.
 */
export const MARKER_MAX_BYTES = 128;

/**
 * Форма метки: та же отбраковка, что у модуля. Алфавита у неё нет -- метку
 * читает человек в журнале, а не загрузчик, -- проверяется лишь то, что
 * мешало бы ей быть строкой журнала: пустота, длина, управляющие символы и
 * крайние пробелы (метка с хвостовым пробелом и без него -- две разные строки
 * в группировке).
 *
 * Возвращает причину отказа либо `null`, если метка годится.
 */
export function markerError(marker: string): string | null {
  if (marker === "") {
    return "mark needs a marker";
  }

  if (new TextEncoder().encode(marker).length > MARKER_MAX_BYTES) {
    return `marker is longer than ${MARKER_MAX_BYTES} bytes`;
  }

  for (const ch of marker) {
    const code = ch.codePointAt(0) ?? 0;

    if (code < 0x20 || code === 0x7f) {
      return "marker has a control character";
    }
  }

  if (marker !== marker.trim()) {
    return "marker has a leading or trailing space";
  }

  return null;
}

