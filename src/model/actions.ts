/**
 * Реестр действий: что инспектор вправе попросить у соседа и какими
 * параметрами это описывается.
 *
 * Словарь живёт в шести местах сразу -- таблицы модуля, константы инспекторов,
 * две таблицы в `docs/inspector-actions.md`, `$defs/action` схемы провода и
 * схема агента, -- и это неизбежно: горячий путь не может ходить за словарём по
 * сети. Неизбежно и то, что копии расходятся, поэтому здесь не седьмая копия, а
 * единственная **машиночитаемая**: её отдаёт API, по ней панель строит
 * селекторы, и тест сверяет её с `docs/messages/inspector.schema.json` -- с тем
 * самым документом, по которому разбирает модуль.
 *
 * Расширение словаря начинается отсюда и из схемы. Панель нового глагола не
 * заметит: список она берёт с ручки, а не из своего файла.
 */

/**
 * Ось: о ком высказывание. Порядок -- от узкого к широкому. response --
 * только у глаголов записи: запись ответа этой транзакции (request у них --
 * запись запроса).
 */
export const ACTION_AXES = ["request", "response", "ip", "asn", "session", "conn"] as const;

export type ActionAxis = (typeof ACTION_AXES)[number];

export const ACTION_VERBS = [
  "challenge",
  "threshold",
  "skip",
  "reauth",
  "note",
  "mutate",
  "active",
  "passive",
  "off",
  "vote",
  "audit",
  "archive",
  "mark",
  "score",
  "ban",
] as const;

export type ActionVerb = (typeof ACTION_VERBS)[number];

/**
 * Параметр глагола. `min`/`max` -- то же, чем модуль отбраковывает ответ: за
 * границей диапазона он выбрасывает не поле, а весь ответ, поэтому панели и
 * инспектору нужны те же числа, а не «примерно такие».
 */
export interface ActionParam {
  name: string;
  /** `object` -- вложенная структура; её форму держит схема провода, реестр только называет поле. */
  type: "int" | "bool" | "string" | "object";
  /** Без параметра действие не имеет смысла, и модуль отвергает ответ. */
  required: boolean;
  min?: number;
  max?: number;
  /**
   * Знак значим: у `delta` он выбирает направление, и правило приёма с именем
   * отправителя в профиле получателя обязательно именно из-за этого.
   */
  signed?: boolean;
}

export interface ActionSpec {
  /** Значение поля `do` на проводе. */
  do: ActionVerb;
  /** Оси, при которых глагол имеет смысл. Прочие модуль отбраковывает. */
  axes: readonly ActionAxis[];
  params: readonly ActionParam[];
  /**
   * Глагол умеет ослаблять защиту получателя. Тихий адресный обход хуже
   * громкой общей аварии, поэтому послабление требует имени отправителя:
   * правило `from: "*"` с таким глаголом загрузчики не принимают
   * (docs/inspector-actions.md, «Кому можно верить не глядя»). Панель по
   * этому признаку не предлагает их широковещательному правилу -- собрать
   * мышью то, что не сохранится, оператор не должен.
   */
  weakens: boolean;
  /**
   * Кто обычно слушает. Подсказка панели, а не ограничение: адресатом может
   * быть любой объявленный инспектор, и проверять это на загрузке нечем --
   * маршруты разные, а запрос идёт по одному.
   */
  listeners: readonly string[];
  /**
   * Глагол исполняет модуль, а не сосед: адресат -- вызов инспектора на
   * маршруте, и правила приёма в профиле получателя у него нет. Панель
   * предлагает такой глагол любому адресату и никогда широковещательно, а в
   * правилах приёма получателей не показывает вовсе.
   */
  module?: boolean;
  /**
   * Адресат -- не вызов соседа, а запись самого маршрута: журнал и архив
   * этого запроса. Поля `to` на проводе нет. Панель показывает такой глагол
   * только псевдоадресату «журнал и архив», ни одному инспектору и не
   * «всем».
   */
  route?: boolean;
  /**
   * Модуль исполняет глагол и от пассивного отправителя: журнал, архив и
   * маркер трафика не касаются, а «что сказал бы выключенный» -- ровно то, ради
   * чего пассивный режим держат. Очки и управляющие глаголы от пассивного
   * модуль отвергает (WARN в лог): на трафик пассивный не влияет. Карточка
   * события по этому признаку отличает «исполнил модуль» от «не исполнено».
   */
  fromPassive?: boolean;
}

/**
 * Глаголы. Словарь короткий намеренно: глагол называет намерение, понятное
 * всему контуру, а частности живут в `code`, которого не толкует никто, кроме
 * пары отправитель-получатель.
 *
 * Глагола «заблокировать» здесь нет и не будет: блокировка -- это вердикт, и он
 * у инспектора свой. Просить соседа отказать вместо себя значило бы размазать
 * ответственность за отказ по двум записям аудита.
 */
/**
 * Осмысленный диапазон коэффициента threshold: проценты к измерению
 * получателя, множитель 1 + delta/100. Минус -- скидка (мягче), плюс --
 * дороже (строже); -100 -- измерение в ноль, +900 -- вдесятеро.
 *
 * Провод как форма несёт целое +-1000 (min/max параметра ниже -- то, чем
 * отбраковывает модуль), а проценты держат загрузчики отправителей: модуль
 * семантику не толкует и не должен, получатель просьбу берёт целиком и
 * прижимает только сумму.
 */
export const THRESHOLD_PERCENT_MIN = -100;
export const THRESHOLD_PERCENT_MAX = 900;

/**
 * Очки на маршруте (`value` у `score`): вклад одного инспектора не сильнее
 * сотни ни в какую сторону -- та же граница, что у вердикта score.
 */
