/**
 * Исходы, на которых просьба архива исполняется (`when` на проводе) -- те же
 * два слова, что у `when=` директивы. Пустой набор -- любой исход, включая
 * перенаправление: просьба сильнее `when=` маршрута, о котором отправитель не
 * знает, и «архивируй что бы ни случилось» -- это отсутствие набора.
 */
/** Предел объекта в архиве, байт: столько же принимает `limit=` директивы. */
export const ARCHIVE_LIMIT_MAX = 1073741824;

export const ARCHIVE_WHEN = ["allow", "deny"] as const;
