import { Router } from "express";

import { ACTIONS, ACTION_AXES, ACTION_COMMON } from "./model/actions.ts";

/**
 * Словарь действий между инспекторами: глаголы, оси, допустимые пары и
 * параметры с их границами.
 *
 * Ручка без области видимости и без базы: это не настройка контура, а форма
 * провода -- одна на все контуры и та же самая, по которой разбирает модуль.
 * Отсюда и отсутствие `:scopeUuid` в адресе, и то, что ответ не зависит ни от
 * чего, кроме версии контроллера.
 *
 * Кому нужна: панели -- чтобы строить селекторы правил и не предлагать пар,
 * которые загрузчик профиля потом отвергнет; всем остальным -- чтобы узнать
 * словарь, не читая исходники пяти сервисов.
 */
export function actionsRouter(): Router {
  const router = Router();

  const body = {
    v: 1,
    axes: ACTION_AXES,
    verbs: ACTIONS,
    common: ACTION_COMMON,
  };

  router.get("/", (_req, res) => {
    /*
     * Кэш надолго: словарь меняется вместе с выкаткой контроллера, а не с
     * настройками, и ходить за ним на каждую отрисовку страницы незачем.
     */
    res.set("Cache-Control", "public, max-age=300");
    res.json(body);
  });

  return router;
}
