-- Каталог инспекторов — справочник доступных процессов, а не заводимые руками
-- записи: строки приезжают с поставкой, имена для маршрутов объявляют в
-- http-конфиге (*.waf.inspectors). Витрине справочника нужны описание и ссылка
-- на документацию. На compile и шину ни то, ни другое не влияет.

alter table inspectors
    add column if not exists description text not null default '',
    add column if not exists docs_url text not null default '';

comment on column inspectors.description is
    'Описание процесса для каталога. На compile и шину не влияет.';
comment on column inspectors.docs_url is
    'Ссылка на документацию процесса. Пусто, пока доков нет.';

-- Только пустые: правку оператора поверх сида не затирать.
update inspectors i
set description = v.description,
    updated_at = now()
from (
    values
        ('modsec',  'Движок правил SecLang (Coraza): CRS и свои наборы, запрос и ответ одной транзакцией.'),
        ('ip',      'IP фильтр: страны, ASN, наборы и списки. Отвечает allow или deny, тело не читает.'),
        ('vlai',    'Классификатор серьёзности: ML-модель оценивает описание в теле, отвечает score.'),
        ('pii',     'Персональные данные в ответе: находит утечку и маскирует находки в теле до клиента.'),
        ('json',    'Контракт API: сверяет вызов с OpenAPI или JSON Schema, читает целое тело фазы из обменника.'),
        ('counter', 'Поведенческий счёт полученного: судит не намерение, а результат — сколько клиент унёс за окно.'),
        ('captcha', 'Капча: испытание подозрительному клиенту, решившим — пропуск по сессии.'),
        ('auth',    'Второй фактор: калитка перед маршрутом — форма и TOTP, пропуск по сессии профиля.'),
        ('auth2',   'Второй фактор: калитка перед маршрутом — форма и TOTP, пропуск по сессии профиля.'),
        ('action',  'Отправитель канала действий: смотрит на маршрут и подсказывает соседям — threshold, note, skip. Сам ничего не проверяет.')
) as v(name, description)
where i.name = v.name
  and i.description = '';
