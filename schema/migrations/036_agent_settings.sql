-- Настройки агента контура: назначения архива и темп выгрузки.
--
-- Отдельная таблица, а не колонка в http_spaces, потому что это другой
-- документ с другой доставкой. Шаблон nginx уезжает поколением, проверяется
-- `nginx -t` и заканчивается reload; здесь нет ни того, ни другого -- агент
-- перечитывает настройку на лету и ни на секунду не трогает трафик. Одна
-- кнопка «сохранить» на два таких документа означала бы, что сохранение
-- одного молча раскатывает другой.
--
-- Что сюда НЕ кладётся:
--
--   * бутстрап агента -- адрес шины, контроллер, ключ ноды, сокет вердиктов.
--     Ими агент дотягивается до шины, и доставить их той же шиной нельзя по
--     кругу зависимостей. Остаются файлом и окружением ноды.
--   * свойства ноды и образа -- bin/conf_dir/store_dir, manage on|off. Они
--     различаются у нод одного контура (раскатку применяет одна, архив ведут
--     все), а документ здесь один на контур.
--   * реквизиты S3. Ключи остаются секретом ноды
--     (WAF_RETAIN_S3_CREDENTIALS_FILE): контроллер их не видит и не хранит,
--     ровно как приватный ключ контура. Здесь только адрес, регион и бакеты.
--
-- Строка одна на пространство: настройка общая для всех его нод.

create table agent_settings (
    http_space_id   uuid primary key references http_spaces(id) on delete cascade,
    -- {s3:{endpoint,region,buckets:{headers,args,body}},
    --  archive:{workers,queue,timeout_ms,batch:{<вид>:{size,timeout_ms}}}}
    settings        jsonb not null default '{}',
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);

comment on table agent_settings is
    'Настройки агента контура: адрес и бакеты архива, темп выгрузки. Реквизиты S3 -- секрет ноды, не здесь.';
