-- Семантика threshold сменилась: delta теперь проценты коэффициента к
-- измерению получателя (множитель 1 + delta/100), и знак перевернулся --
-- раньше плюс поднимал порог получателя (смягчал), теперь плюс делает
-- поведение клиента дороже (строже), минус -- скидка.
--
-- Существующие правила написаны в старой конвенции: их направление обязано
-- пережить переезд, поэтому знак переворачивается, а величина прижимается к
-- новому диапазону -100..+900. Величина старых правил была в единицах порога
-- получателя, то есть точного перевода в проценты не существует; знак -- вся
-- семантика, которую можно сохранить честно, и оператору стоит перечитать
-- свои threshold-правила после переезда.

update ip_profile_rules
   set delta = greatest(-100, least(900, -delta))
 where do_verb = 'threshold'
   and delta is not null;
