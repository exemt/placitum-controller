-- hash=md5 у набора строк: состав хранит md5 значений в hex, а не сами
-- значения. Всё, что сравнивается с набором или пишет в него -- check, if,
-- автобан rate, keeper, панель -- хеширует значение само. Набор сессий и
-- токенов не держит ни строки длиннее 32 байт, ни секрета открытым текстом.
--
-- Только у kind=list с type=string; адресу и числу хеш ничего не даёт --
-- проверяет API, а не ограничение: тип набора и так не меняется.

alter table datasets
    add column if not exists hash boolean not null default false;
