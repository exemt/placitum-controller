-- Фраза клиенту снята у type=http: текст отказа -- свойство самой страницы
-- ("Данные -> Файлы"), и второе место под ту же фразу расходилось бы с ней
-- молча. У grpc и websocket поле остаётся: сказать там иначе нечем.
--
-- Значение вычищается, а не игнорируется. Панель поля больше не показывает, а
-- компилятор его не печатает: строка, оставшаяся в spec, была бы невидимой
-- правкой -- никто её уже не найдёт и не отменит.
update deny_responses
   set spec = spec - 'message'
 where type = 'http'
   and spec ? 'message';
