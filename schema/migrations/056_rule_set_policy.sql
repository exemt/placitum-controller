-- Политика профиля правил: обе стороны канала действий в одном документе --
-- правила приёма чужих просьб (prior) и инициаторы по исходу (outcomes).
--
-- Документ jsonb, а не таблица: форма повторяет policy.yaml инспектора и
-- меняется вместе с ним, колонка на поле заставляла бы мигрировать базу на
-- каждое новое поле -- как у профилей адреса (053) и капчи.
--
-- До этой миграции политика жила только файлом в образе инспектора и
-- переставала действовать после первой отправки правил: применённое дерево
-- подменяет каталог профилей целиком. Теперь она едет в паке своим слотом.

alter table rule_sets
  add column if not exists policy jsonb not null default '{}'::jsonb;
