-- Профиль калитки заводят на конкретный сервер.
--
-- Само решение о допуске от сервера не зависит: профиль выбирается тегом
-- profile= записи реестра, и один профиль технически может обслуживать
-- маршруты разных серверов. Но адрес формы -- это location, а location
-- принадлежит серверу, и выбирать его вслепую из текстового поля значит
-- проверять совпадение уже на стенде: опечатка в пути даёт бесконечный
-- редирект и никакой ошибки в UX.
--
-- Поэтому привязка: сервер называет, из какого списка локейшенов выбирать
-- login.uri, и контроллер проверяет, что выбранный существует и объявлен с
-- waf off.
--
-- Колонка допускает NULL: профили, заведённые до этой миграции, и профили
-- режима observe (у которых адреса формы нет вовсе) сервера не требуют.

alter table auth_profiles
    add column if not exists server_id uuid references servers(id) on delete cascade;

create index if not exists auth_profiles_server on auth_profiles (server_id);

comment on column auth_profiles.server_id is
    'Сервер, из локейшенов которого выбран login.uri. NULL -- профиль без формы.';
