-- Преднастроенные списки адресов: default_allowlist и default_blocklist.
--
-- Пустой раздел «Данные -> Списки» встречает оператора вопросом «с чего
-- начать»: под первое исключение или первый бан надо сначала придумать набор,
-- его тип и имя. Заготовки снимают этот шаг: пара списков под очевидные роли
-- есть в каждом пространстве с поставки, их остаётся наполнить и включить
-- туда, где они нужны, -- в составной набор, правило профиля или слот
-- локального слоя. Сами по себе они ничего не решают: список -- это ответ на
-- «кто это», действие задаёт тот, кто его включил.
--
-- builtin -- как у страниц отказа (062): запись нельзя ни удалить, ни
-- переименовать, поэтому на имена заготовок можно ссылаться в документации и
-- пресетах, не проверяя каждый раз, целы ли они. Всё остальное -- состав,
-- описание, лимит, режим active -- правится свободно: на то она и заготовка.
--
-- Тип ip (IPv4 + IPv6): отдельного v6-типа у наборов нет, и заготовка не
-- должна заставлять выбирать семейство заранее. Режим -- internal: active
-- означает подписку края на шину, и включать её за оператора миграция не
-- вправе.
--
-- Сеется, как 060 и 062: в каждое пространство, если имя ещё не занято.
-- Чужому набору с таким именем builtin не проставляется: запрет на удаление
-- тому, кто его не просил, -- это ловушка, а не защита.

do $$
declare
    item record;
begin
    for item in
        select s.id as space, l.name, l.note
          from http_spaces s
          cross join (values
            ('default_allowlist',
             'Стандартный список разрешаемых адресов, пустой с поставки'),
            ('default_blocklist',
             'Стандартный список блокируемых адресов, пустой с поставки')
          ) as l(name, note)
         order by s.id, l.name
    loop
        if exists (select 1 from datasets d
                    where d.http_space_id = item.space and d.name = item.name) then
            continue;
        end if;

        insert into datasets (http_space_id, name, description, subject,
                              kind, type, max_entries, builtin)
        values (item.space, item.name, item.note, 'waf.data.' || item.name,
                'list', 'ip', 1000000, true);
    end loop;
end $$;
