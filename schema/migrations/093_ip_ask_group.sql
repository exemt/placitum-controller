-- mutate у строк IP фильтра.
--
-- Переключить группу модификаторов ответа у rewrite умели только счётчик и
-- инспектор действий: у остальных отправителей канала глагола не было ни в
-- таблице исходов, ни в документе. Сценарий «адрес из набора -- включить
-- маскировку ответа» собирался мышью (панель берёт словарь из реестра) и
-- отвергался контроллером четырёхсоткой.
--
-- Группу называет отправитель, как корзину у note; куда переключить -- та же
-- сторона, что у глаголов записи (ask_set у строки, set у инициатора).
-- Инициаторы держат её в том же jsonb, правилам нужна колонка.
alter table ip_profile_rules
    add column if not exists ask_group text not null default '';

comment on column ip_profile_rules.ask_group is
    'Группа модификаторов получателя при do: mutate; куда переключить -- ask_set. Пусто у остальных глаголов.';
