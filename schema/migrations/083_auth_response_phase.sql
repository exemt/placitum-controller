-- Фаза ответа у калитки: провайдер app подсматривает вход приложения на фазе
-- ответа маршрута входа (docs/README.md репозитория auth, «app»). Каталог
-- утверждал, что auth умеет только запрос (048 оставила его запросом --
-- тогда так и было), и объявление калитки на фазе ответа не собиралось:
-- компилятор разворачивает `waf_inspect response` только в тех, кто фазу
-- умеет.
--
-- Своя калитка и jwt на ответе по-прежнему отвечают AUTH_PHASE_NOT_SUPPORTED:
-- запрет живёт в самом инспекторе, каталог лишь перестаёт его дублировать.

update inspectors
   set phases     = array['request', 'response']::text[],
       updated_at = now()
 where subject = 'waf.req.auth'
   and not ('response' = any(phases));
