-- Фазы записей каталога: набор появился в 035, но заполнен не был.
--
-- 035 добавила `phases` и перенесла в неё старую колонку `phase` как есть:
-- `update inspectors set phases = array[phase]`. У всех записей там стоял
-- 'request', потому что другой колонка и не бывала -- одна фаза на запись как
-- раз и была тем, что миграция снимала. В итоге набор завели, а содержимое
-- осталось прежним: каталог утверждал, что фазу ответа не умеет никто.
--
-- Цена этого видна в компиляторе: `waf_inspect response all` разворачивается
-- в тех, кто фазу умеет (nginx-emit, expandInspects), то есть в пустой
-- список. Фаза ответа была объявлена сквозной и при этом недостижимой из
-- панели -- ни одной строки `waf_inspect response` не печаталось.
--
-- Кто ведёт обе стороны:
--
--   modsec -- одна транзакция движка правил, фазы 1-2 на запросе и 3-4 на
--             ответе (`keep=on` / `resume=`, docs/README.md репозитория modsec).
--   pii    -- обе функции, и оценка утечки, и маска, смотрят тело ответа;
--             фаза запроса у него -- отладка и прогон.
--
-- ip, vlai, auth, captcha остаются запросом: решение принимается до
-- проксирования, и на ответе спрашивать их не о чем.

update inspectors
   set phases     = array['request', 'response']::text[],
       updated_at = now()
 where name in ('modsec', 'pii')
   and phases = array['request']::text[];
