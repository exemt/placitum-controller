-- Инспектор адреса называется «IP фильтр».
--
-- Имя на проводе прежнее (`ip`: subject waf.req.ip, каталог политики, ключ
-- профиля) -- переименовано только то, что читает человек. Заодно из описания
-- уходит `score`: счёта у этого инспектора больше нет
-- (086_ip_raw_lists_no_score.sql), и каталог обещал бы вердикт, которого он не
-- выносит.
update inspectors
   set description = 'IP фильтр: страны, ASN, наборы и списки. Отвечает allow или deny, тело не читает.'
 where name = 'ip';
