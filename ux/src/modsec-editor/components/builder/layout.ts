/**
 * Общие размеры колонок конструктора.
 *
 * Условие рисуется тремя независимыми компонентами — области проверки,
 * конвейер преобразований и сравнение, — но читаться должно как одна
 * таблица. Поэтому ширины служебных колонок вынесены сюда: каждая из них
 * резервируется всегда, даже когда кнопки в строке нет. Иначе строка без
 * крестика «Убрать» уезжает влево и вертикали ломаются.
 *
 * По той же причине здесь и ширины полей, которые повторяются в разных
 * панелях: фазу с реакцией спрашивают и действия правила, и умолчания
 * `SecDefaultAction`, выборку правил — и директива-исключение, и запись
 * `ctl`. Панели стоят в одном файле друг под другом, и колонки, разошедшиеся
 * на десятки точек, читаются как разные поля, хотя спрашивают одно и то же.
 *
 * Здесь только ширины. Высота строки общая для всего интерфейса и живёт в
 * теме — `CONTROL_HEIGHT`.
 */

/** Колонка под иконочную кнопку (крестик, корзина). */
export const ICON_COLUMN = 32;

/**
 * Колонка раскрывашки — по габариту иконочной кнопки в шапке карточки.
 *
 * Шапка правила и блоки под ней держат значок в колонке одной ширины: иначе
 * взгляд ищет раскрывашку заново на каждом уровне вложенности.
 */
export const CHEVRON_COLUMN = 28;

/**
 * Колонка названия — одна на все уровни конструктора.
 *
 * В ней стоит то, чем блок зовётся: номер правила, имя директивы, разряд
 * метки, название блока внутри карточки. Сразу за ней начинается содержимое —
 * описание правила, аргумент директивы, выжимка блока, — и начинается оно у
 * всех на одной вертикали. Своя ширина у каждого разряда строки и есть тот
 * разнобой, из-за которого список блоков читается не одной таблицей, а
 * несколькими, положенными друг под друга.
 *
 * Меру задаёт самое длинное имя директивы: `SecResponseBodyMimeTypesClear` —
 * двадцать девять моноширинных знаков, и обрезанное имя пришлось бы сверять с
 * текстовой вкладкой по началу. Короткому «Правилу 942100» столько места не
 * нужно, но пустое место в колонке дешевле, чем колонка, гуляющая от строки к
 * строке.
 */
export const TITLE_COLUMN = 236;

/** Колонка под ручку перетаскивания преобразования. */
export const HANDLE_COLUMN = 24;

/** Колонка под квадратный переключатель — `&` у области и `!` у оператора. */
export const TOGGLE_COLUMN = 40;

/** Поле выбора оператора. */
export const OPERATOR_COLUMN = 170;

/**
 * Секция областей проверки: поле переменной со списком её параметров под ним.
 *
 * Мера общая у условия и у обеих форм исключения — секция в них одна и та же,
 * и набирают в ней одно и то же. Своей ширины у секции нет: она берёт место,
 * которое ей отвели, и отведённое «сколько есть» выходило под тысячу точек —
 * поле во всю карточку под словом `ARGS`. Одна и та же секция в условии и в
 * директиве читалась при этом как две разные.
 */
export const TARGET_COLUMN = 480;

/**
 * Поле выборки в исключении: номера правил, сообщение или метка.
 *
 * Общее у директивы-исключения и у записи `ctl`: выбирают в них одинаково.
 * Ширина — под несколько номеров чипами, потому что по одному правила снимают
 * редко: `942100 942110 942120` в колонке поуже ложится по номеру в строку и
 * растит панель втрое.
 */
export const PICK_COLUMN = 260;

/**
 * Поле фазы. Под самое длинное название целиком — «1 — Заголовки запроса», —
 * с запасом на кнопку очистки и стрелку списка.
 */
export const PHASE_COLUMN = 260;

/** Поле реакции: та же мера, под «Разорвать соединение». */
export const REACTION_COLUMN = 250;

/** Поле кода ответа: три цифры и стрелка списка. */
export const STATUS_COLUMN = 160;

/** Поле трёхпозиционного флага — `log`/`nolog`, `auditlog`/`noauditlog`. */
export const FLAG_COLUMN = 190;

/**
 * Поле коллекции у присваивания. Под самое длинное название целиком —
 * «SESSION — по сессии», — со стрелкой списка.
 */
export const COLLECTION_COLUMN = 210;

/**
 * Поле вида записи: «задать», «прибавить», «вычесть», «удалить» со знаком,
 * которым каждое из них пишется в правиле.
 */
export const SETVAR_OP_COLUMN = 150;

/** Полоса преобразований целиком: ручка + выпадающий список + крестик. */
export const TRANSFORM_COLUMN = 260;

/** Ширина скобки логической связки вместе с подписью. */
export const BRACKET_WIDTH = 46;

/** Внутреннее поле блока условия, в единицах `theme.spacing`. */
export const CONDITION_PADDING = 1.25;

/**
 * Верхнее поле блока условия. Больше остальных: подписи полей стоят выше
 * их верхнего края, и с общим полем первая строка почти касается края блока.
 */
export const CONDITION_PADDING_TOP = 1.75;
