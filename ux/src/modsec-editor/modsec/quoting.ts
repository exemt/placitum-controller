/**
 * Запись значений в списках ModSecurity.
 *
 * `ARGS:token` и `msg:text` выглядят так, будто значение — это просто текст
 * после двоеточия. Но текст этот живёт внутри двух чужих грамматик сразу,
 * и обе его ограничивают.
 *
 * Сверху — разбор строки директивы: она режется по пробелам, поэтому список
 * переменных с пробелом внутри обязан целиком стоять в двойных кавычках
 * (список действий в них стоит всегда). Снизу — разбор самого списка:
 * неквотированное значение обрывается на пробеле, `,` и `|`, а в одинарных
 * кавычках допустимы ровно две экранированные пары, `\'` и `\\`.
 *
 * Списки переменных и действий разбирает одна и та же функция движка
 * (`msre_parse_generic`), поэтому правила записи у них общие — и живут
 * здесь в одном экземпляре. Разные у них только последствия: в действиях
 * значение задаёт человек и почти всегда безобидно, а в параметре области
 * проверки легко оказывается имя аргумента с пробелом.
 *
 * Модель хранит значения уже разобранными: `my param`, а не `'my param'`.
 * Кавычки — это запись, а не значение, и решать, нужны ли они, должен
 * вывод, а не человек, набирающий имя аргумента.
 *
 * Записать так можно не всё. ModSecurity 3 разбирает список переменных
 * собственным лексером: кавычки он допускает только вокруг шаблона
 * (`'/^id_/'`) и содержимое берёт буквально — без разэкранирования, которое
 * делает вторая версия. Значит, для параметра, где нужны и кавычки, и
 * обратный слэш, единой записи не существует: один и тот же текст движки
 * прочитают по-разному. Такие значения кодек записывает по правилам второй
 * версии, а {@link selectorIssue} их помечает — предупредить честнее, чем
 * молча выбрать одну из двух несовместимых трактовок.
 *
 * Известный пробел в проверке: третья версия не принимает `=` внутри
 * шаблона (`ARGS:/^a=b$/`). Случай слишком редкий, чтобы держать ради него
 * ещё одно сообщение, но при расширении проверок про него стоит помнить.
 */

/** Символы, из-за которых значение нельзя записать без кавычек. */
const NEEDS_QUOTES = /[\s|,'"]/;

/** Метасимволы шаблона, которые в имени параметра значат сами себя. */
const REGEX_META = /[.\\+*?()[\]{}^$|/]/g;

export function needsQuotes(value: string): boolean {
  return NEEDS_QUOTES.test(value);
}

/** Снимает с записи значения одинарные кавычки и экранирование. */
export function decodeQuoted(raw: string): string {
  if (raw.length < 2 || !raw.startsWith("'") || !raw.endsWith("'")) return raw;
  return raw.slice(1, -1).replace(/\\(['\\])/g, '$1');
}

/** Записывает значение так, чтобы оно прочиталось обратно тем же самым. */
export function encodeQuoted(value: string): string {
  if (!needsQuotes(value)) return value;
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** Параметр записан шаблоном (`/^id_/`), а не именем. */
export function isPatternSelector(value: string): boolean {
  return value.length >= 2 && value.startsWith('/') && value.endsWith('/');
}

/**
 * Чем запись параметра области проверки рискованна; `null` — ничем.
 *
 *  - `v2only` — понадобятся кавычки, и такую запись прочитает только вторая
 *    версия; для пробела в имени есть замена ({@link selectorPattern});
 *  - `ambiguous` — версии прочитают запись по-разному, замены нет.
 */
export type SelectorIssue = 'v2only' | 'ambiguous';

export function selectorIssue(value: string): SelectorIssue | null {
  if (value === '' || !needsQuotes(value)) return null;
  // Кавычка и обратный слэш требуют разэкранирования, которое есть только
  // во второй версии: третья вернёт текст как есть, вместе со слэшами.
  if (/['\\]/.test(value)) return 'ambiguous';
  // Кавычки вокруг шаблона понимают обе версии — но пробел внутри них
  // третья не пропускает, чем бы этот шаблон ни был.
  if (isPatternSelector(value) && !/\s/.test(value)) return null;
  return 'v2only';
}

/**
 * Замена имени с пробелом на шаблон, которому пробел не мешает.
 *
 * `my param` → `/^my\x20param$/`. Пробел записан кодом символа, а не `\s`:
 * тот совпал бы ещё и с табуляцией, а имя аргумента может содержать и её —
 * проверка стала бы шире, чем просили.
 *
 * `null`, когда замены нет: чинить нечего либо в имени есть символ, из-за
 * которого шаблон всё равно придётся взять в кавычки.
 */
export function selectorPattern(value: string): string | null {
  if (!/\s/.test(value)) return null;
  if (/[|,'"]/.test(value)) return null;

  const body = value
    .replace(REGEX_META, (ch) => `\\${ch}`)
    .replace(/ /g, '\\x20')
    .replace(/\t/g, '\\x09');
  return `/^${body}$/`;
}
