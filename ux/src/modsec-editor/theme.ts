import { alpha, createTheme } from '@mui/material/styles';
import type { Theme } from '@mui/material/styles';

/**
 * Высота управляющего элемента строки: поля, переключателя, набора чипов.
 *
 * Конструктор читается как таблица, поэтому все элементы одной строки
 * обязаны совпадать по высоте. Значение нужно не только теме: скобки связок
 * и кнопки, вынесенные из потока сетки, встают на линию полей по этому же
 * числу — иначе они уезжают на пару пикселей и вертикали ломаются.
 */
export const CONTROL_HEIGHT = 32;

/**
 * Высота полосы заголовка блока конструктора: одна строка органов управления
 * плюс поля сверху и снизу.
 *
 * Задана числом, а не собрана из содержимого, потому что по ней считаются
 * распорки виртуализированного списка: чтобы не рисовать тысячу свёрнутых
 * блоков, надо знать высоту одного заранее, а не после того, как он
 * нарисовался. Полосу заголовка имеют все блоки — и правило, и метка, и
 * директива, — поэтому свёрнутый список идёт ровным шагом.
 */
export const BLOCK_ROW = CONTROL_HEIGHT + 16;

/**
 * Горизонтальный отступ внутри поля.
 *
 * По нему выравнивается всё содержимое — текст, чипы, плавающая подпись, —
 * поэтому левые края соседних полей совпадают независимо от начинки. Поле,
 * которое собирает содержимое само, обязано брать отступ отсюда: иначе оно
 * встанет в общий ряд со сдвигом в пару пикселей.
 */
export const FIELD_GUTTER = 10;

/** Подъём свёрнутой подписи над верхней рамкой поля. */
const LABEL_LIFT = 9;

/**
 * Верхний отступ содержимого окна, в котором стоит поле ввода.
 *
 * Свёрнутая подпись выходит за верхний край поля, а MUI под заголовком окна
 * снимает верхний отступ содержимого и прокручивает его — подпись первого
 * поля срезается краем прокрутки. Отступ оставляет место подписи целиком и
 * ещё немного, чтобы она не лежала на самом краю.
 */
export const DIALOG_FIELD_TOP = LABEL_LIFT + 3;

/**
 * Кнопки внутри поля: значок, поле вокруг него, просвет между соседями и
 * отступ всего ряда от правого края.
 *
 * Ряд справа от значения собирается из разных источников — карандаш ставит
 * поле, крестик и стрелку добавляет выпадающий список, — и у каждого свои
 * умолчания: стрелка приходит на четверть крупнее соседей, а просветы между
 * кнопками у MUI разные вплоть до отрицательных. Ряд из-за этого читается
 * набором случайных значков, поэтому размеры заданы здесь и навязываются
 * любой кнопке в поле, чьей бы она ни была.
 *
 * Отступ ряда — тот же, что у поля с любым содержимым справа: значок
 * встаёт от края на то же расстояние, что и текст слева.
 */
const FIELD_ACTION_ICON = 18;
const FIELD_ACTION_PAD = 3;
const FIELD_ACTION_GAP = 2;
export const FIELD_ACTION_INSET = FIELD_GUTTER - 4;

/**
 * Высота кнопки в поле: значок со своими полями.
 *
 * Самое высокое в строке поля — эта кнопка, поэтому по ней считается и
 * высота строки в поле, которое собирает содержимое само: набор чипов
 * обязан оставить ряду кнопок ровно строку, не больше и не меньше.
 */
export const FIELD_ACTION_HEIGHT = FIELD_ACTION_ICON + 2 * FIELD_ACTION_PAD;

/**
 * Высота чипа-значения.
 *
 * Чип ниже строки поля, и поднимать его до её середины приходится тому, кто
 * строку собирает, — поэтому число нужно не только теме.
 */
export const CHIP_HEIGHT = 20;

/**
 * Поле выпадающего списка сверху и снизу.
 *
 * Заголовок раздела прилипает к верхнему краю списка и обязан закрыть это
 * поле собой — иначе в просвет над ним видно уезжающие вверх строки, —
 * поэтому число нужно и списку, и заголовку.
 */
export const LIST_PADDING = 4;

/** Ширина полосы, которой список отмечает уже выбранный вариант. */
const LIST_ACCENT = 2;

/**
 * Поле вокруг значка в иконочной кнопке.
 *
 * Число нужно не только теме: тот, кто собирает из таких кнопок ряд, считает
 * по нему свои отступы. Просвет разметки складывается с этим полем, поэтому
 * одинаковые на вид отступы дают разные просветы — до подписи один, между
 * значками вдвое больший, — и вычитать поле приходится там, где ряд строится.
 */
export const ICON_BUTTON_PAD = 4;

/**
 * Скругление углов. Правило ModSecurity — техническая конструкция из
 * прямоугольных блоков, и мягкие овалы её только размывают: чем ближе
 * элементы к прямоугольнику, тем очевиднее, что они лежат в одной сетке.
 */
const RADIUS = 4;

/** Внутренняя высота поля: то, что остаётся под содержимое без рамки. */
const CONTENT_HEIGHT = CONTROL_HEIGHT - 2;

/** Строка текста в поле при базовом кегле — по ней считаются отступы. */
const LINE_HEIGHT = 19;

/** Вертикальный отступ, доводящий строку текста до высоты элемента. */
const PAD_Y = (CONTENT_HEIGHT - LINE_HEIGHT) / 2;

/**
 * Тёмная тема конструктора.
 *
 * Цвета — смысловые, а не декоративные: оранжевый закреплён за областями
 * проверки и связкой ИЛИ, красный — за связкой И и разрушающими действиями,
 * бирюзовый — за операторами сравнения, фиолетовый — за преобразованиями.
 * Один и тот же цвет означает одно и то же в любом месте интерфейса.
 *
 * Размеры собраны здесь целиком и намеренно: стандартные отступы MUI
 * рассчитаны на формы в полстраницы, а здесь в одну строку укладывается
 * целая директива. Задавать компактность на каждом поле по отдельности
 * значит гарантированно получить поля разной высоты — что и случилось с
 * исключениями, — поэтому плотность задаётся один раз для всего проекта.
 *
 * Тема собирается функцией, а не лежит готовой: редактор открывают окном
 * внутри панели, и два числа приходят оттуда.
 */
export interface EditorThemeOptions {
  /**
   * Слои панели, в которой редактор открыт окном.
   *
   * Умолчания MUI (окно 1300, подсказка 1500) ниже окна панели: её диалоги
   * подняты до 4000, и меню, окна и подсказки редактора уходили бы под то
   * самое окно, в котором он показан.
   */
  zIndex?: Partial<Theme['zIndex']>;
  /**
   * Базовый кегль в пикселях при корне документа 16px.
   *
   * Сам по себе редактор считает от 13. Панель ужимает корень документа до
   * 80%, и все rem-размеры темы ужимаются вместе с ним: чтобы текст остался
   * тем же, что в самостоятельном редакторе, кегль поднимают на ту же долю —
   * 13 / 0.8 ≈ 16.
   */
  fontSize?: number;
}

export function createEditorTheme({
  zIndex,
  fontSize = 13,
}: EditorThemeOptions = {}): Theme {
  return createTheme({
  // `zIndex: undefined` не пропускается: слияние темы положило бы его как
  // есть, и у окон не осталось бы слоя вовсе.
  ...(zIndex === undefined ? {} : { zIndex }),
  palette: {
    mode: 'dark',
    background: { default: '#181b21', paper: '#22262e' },
    primary: { main: '#8b7ce8', light: '#b9a9ff' },
    secondary: { main: '#3fd0c9', light: '#7fe3dd' },
    error: { main: '#e05a4f', light: '#f08a80' },
    warning: { main: '#e8974a', light: '#f0b070' },
    success: { main: '#5ab98a' },
    divider: 'rgba(255,255,255,0.12)',
    text: { primary: '#e6e8ec', secondary: '#98a1b0' },
  },
  shape: { borderRadius: RADIUS },
  typography: { fontSize },
  components: {
    MuiPaper: { styleOverrides: { root: { backgroundImage: 'none' } } },

    // Размер полей не оставлен на усмотрение места вызова: «small» —
    // единственный размер, в котором строка условия остаётся строкой.
    MuiTextField: { defaultProps: { variant: 'outlined', size: 'small' } },
    MuiFormControl: { defaultProps: { size: 'small' } },
    MuiAutocomplete: {
      defaultProps: { size: 'small' },
      // Autocomplete считает отступы поля сам, поверх обычного поля ввода.
      // Повторяем его же селектор, чтобы список переменных не оказался
      // выше соседних полей.
      styleOverrides: {
        root: {
          '& .MuiOutlinedInput-root.MuiInputBase-sizeSmall': {
            paddingTop: PAD_Y,
            paddingBottom: PAD_Y,
            paddingLeft: FIELD_GUTTER - 4,
            '& .MuiAutocomplete-input': { padding: '0 4px' },
          },

          // Место под крестик и стрелку список отводит полем справа, считая
          // их положение абсолютным, и тем шире, чем их больше. Ряд теперь
          // стоит в потоке и место занимает своё, поэтому запас снимается —
          // иначе справа от стрелки остаётся полоса шире её самой. Оба
          // признака перечислены вместе не для красоты: селектор обязан
          // весить не меньше исходного, иначе он его не перебьёт.
          '&.MuiAutocomplete-hasPopupIcon, &.MuiAutocomplete-hasClearIcon, &.MuiAutocomplete-hasPopupIcon.MuiAutocomplete-hasClearIcon':
            {
              '& .MuiOutlinedInput-root': { paddingRight: FIELD_ACTION_INSET },
            },
        },

        // Служебные кнопки списка вынуты из абсолютного угла в общий ряд:
        // рядом с ними встают кнопки самого поля — карандаш «править в
        // окне», — и порядок в ряду должен быть один, а не «эти поверх тех».
        endAdornment: {
          // Сдвиг на половину высоты поднимал ряд к середине поля, пока он
          // стоял вне потока; в потоке его выравнивает сама строка.
          position: 'static',
          transform: 'none',
          display: 'flex',
          alignItems: 'center',
          flexShrink: 0,
          gap: `${FIELD_ACTION_GAP}px`,
          // Высоту поля ряд не задаёт — по той же причине, по которой её не
          // задаёт карандаш: кнопка выше строки текста, и поле со списком
          // стало бы выше соседей.
          marginTop: -PAD_Y,
          marginBottom: -PAD_Y,
          '& .MuiSvgIcon-root': { fontSize: FIELD_ACTION_ICON },
        },
        clearIndicator: { padding: FIELD_ACTION_PAD, margin: 0 },
        popupIndicator: { padding: FIELD_ACTION_PAD, margin: 0 },

        // Панель списка всплывает над блоком условия, а фон у них почти
        // одинаковый: без рамки и тени не видно, где кончается страница и
        // начинается список. Обрезка по краю нужна подвалу — кнопка «все
        // варианты» растянута во всю ширину и без неё торчит из скруглений.
        paper: ({ theme }) => ({
          border: `1px solid ${theme.palette.divider}`,
          boxShadow: theme.shadows[8],
          overflow: 'hidden',
        }),

        // Строка списка здесь двухэтажная — название и пояснение под ним, —
        // и отступы MUI, рассчитанные на одну строку текста, растягивают
        // список так, что за раз видно вариантов пять. Левый край строки
        // совпадает с левым краем текста в поле: список читается как
        // продолжение поля, а не как отдельная таблица.
        listbox: ({ theme }) => ({
          padding: `${LIST_PADDING}px 0`,
          // Светлая полоса прокрутки на тёмной панели выглядит прорехой.
          scrollbarWidth: 'thin',
          scrollbarColor: `${alpha('#ffffff', 0.18)} transparent`,
          '& .MuiAutocomplete-option': {
            paddingLeft: FIELD_GUTTER - LIST_ACCENT,
            paddingRight: FIELD_GUTTER,
            // Уже выбранный вариант в тёмной теме отличается от соседей
            // только слабой заливкой, и в длинном списке его приходится
            // искать. Полоса слева видна с любого места; место под неё
            // отведено у всех строк, иначе выбор сдвигал бы текст.
            borderLeft: `${LIST_ACCENT}px solid transparent`,
            '&[aria-selected="true"]': { borderLeftColor: theme.palette.primary.main },
          },
        }),
      },
    },

    MuiOutlinedInput: {
      styleOverrides: {
        // Размер поля здесь читается из `ownerState`, а не из класса: у
        // самого `input` класса размера нет, MUI различает размеры только
        // вариантами. У многострочного поля отступы держит корпус, а не
        // сам `textarea`, — ему padding задавать нельзя, он сложится с
        // корпусом и текст уедет от рамки вдвое дальше.
        input: ({ ownerState, theme }) => {
          // Растянутый переход одного `background-color` держит на месте
          // только исходный синий или жёлтый фон автозаполнения — менеджеры
          // паролей заливают поле собственным цветом уже поверх него, и тот
          // же приём его не берёт. Заливка через `box-shadow` рисуется над
          // любым таким фоном всегда, поэтому здесь оставлен едва заметный
          // оттенок акцента, а не попытка притвориться, что поле пустое:
          // заметно, что оно найдено автозаполнением, но не ярче обычного
          // поля в фокусе.
          const autofillTint = {
            WebkitTextFillColor: '#e6e8ec',
            caretColor: '#e6e8ec',
            WebkitBoxShadow: `0 0 0 1000px ${alpha(theme.palette.primary.main, 0.07)} inset`,
            transition: 'background-color 600000s ease-in-out 0s',
          };
          return {
            ...(ownerState.size === 'small' && !ownerState.multiline
              ? { padding: `${PAD_Y}px ${FIELD_GUTTER}px` }
              : {}),
            // Хром переопределяет заливку по отдельности для каждого из
            // этих состояний — своего правила без них хватает только на
            // поле, которое ни разу не тронули.
            '&:-webkit-autofill': autofillTint,
            '&:-webkit-autofill:hover': autofillTint,
            '&:-webkit-autofill:focus': autofillTint,
          };
        },
        root: {
          '&.MuiInputBase-adornedStart': { paddingLeft: FIELD_GUTTER },
          '&.MuiInputBase-adornedEnd': { paddingRight: FIELD_ACTION_INSET },
        },
      },
    },

    // Плавающая подпись едет вслед за отступом поля: в свёрнутом виде она
    // стоит на месте будущего текста, в развёрнутом — в разрыве рамки.
    MuiInputLabel: {
      styleOverrides: {
        sizeSmall: {
          transform: `translate(${FIELD_GUTTER}px, ${PAD_Y}px) scale(1)`,
          '&.MuiInputLabel-shrink': {
            transform: `translate(${FIELD_GUTTER}px, -${LABEL_LIFT}px) scale(0.75)`,
          },
        },
      },
    },

    MuiButton: {
      defaultProps: { size: 'small' },
      styleOverrides: {
        // Кнопки конструктора подписаны по-русски и длинной подписи им
        // хватает: резерв в 64px из умолчаний MUI только раздувает строку.
        sizeSmall: { padding: '2px 8px', minWidth: 0 },
      },
    },

    // Иконочные кнопки квадратные, а не круглые: они стоят в колонках
    // сетки, и круглая подсветка при наведении выпадает из этих колонок.
    MuiIconButton: {
      defaultProps: { size: 'small' },
      styleOverrides: { sizeSmall: { padding: ICON_BUTTON_PAD, borderRadius: RADIUS } },
    },

    // Кнопка внутри поля не задаёт его высоту. Иконка с полями кнопки выше
    // строки текста, и поле значения с карандашом становилось на пять
    // пикселей выше соседей — строка условия переставала читаться таблицей.
    // Кнопка забирает вертикальные поля поля ввода себе: в габарит она
    // укладывается и без них, а высоту теперь задаёт только строка текста.
    //
    // Держит их сама обойма, а не кнопка внутри: у обоймы своя высота в
    // сотую долю строки, и кнопка, вычитавшая поля из себя, вставала на
    // полпикселя выше служебных соседок. Ряд собран из чужих кнопок, и
    // сходиться они обязаны точно.
    MuiInputAdornment: {
      styleOverrides: {
        root: {
          // Своя кнопка поля стоит последней в ряду служебных, и просвет до
          // соседки у неё тот же, что у них между собой.
          '&.MuiInputAdornment-positionEnd': {
            marginLeft: FIELD_ACTION_GAP,
            height: 'auto',
            marginTop: -PAD_Y,
            marginBottom: -PAD_Y,
          },
          '& .MuiSvgIcon-root': { fontSize: FIELD_ACTION_ICON },
          '& .MuiIconButton-root': { padding: FIELD_ACTION_PAD },
        },
      },
    },

    MuiToggleButton: {
      styleOverrides: {
        sizeSmall: { height: CONTROL_HEIGHT, padding: `0 ${FIELD_GUTTER - 2}px` },
        // Включённое состояние держится на цвете, а не на подсветке фона:
        // серая заливка из умолчаний в тёмной теме почти не отличается от
        // выключенной кнопки, и по переключателю нельзя сказать, действует
        // он сейчас или нет. Цвет задаётся на месте — `error` у отрицания,
        // `success` у подсчёта, — и рамка подхватывает его же.
        root: { '&.Mui-selected': { borderColor: 'currentColor' } },
      },
    },

    // Чип — это значение списка, а не ярлык: он стоит внутри поля рядом с
    // текстом, поэтому повторяет его форму, а не форму таблетки.
    MuiChip: {
      defaultProps: { size: 'small' },
      styleOverrides: {
        sizeSmall: { height: CHIP_HEIGHT, borderRadius: RADIUS - 1 },
        label: ({ ownerState }) =>
          ownerState.size === 'small' ? { paddingLeft: 6, paddingRight: 6 } : {},
        deleteIcon: ({ ownerState }) =>
          ownerState.size === 'small' ? { fontSize: 15, marginRight: 3 } : {},
      },
    },
  },
  });
}
